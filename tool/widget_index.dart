// Generates WIDGETS.md: an index of everything the package exports.
//
// Run from the package root:  dart run tool/widget_index.dart
// test/widget_index_test.dart fails when WIDGETS.md is out of date.
import 'dart:io';

const String outputFile = 'WIDGETS.md';

final RegExp _export = RegExp(r"^export\s+'([^']+)'", multiLine: true);
final RegExp _declaration = RegExp(
  r'^(?:(?:abstract|sealed|base|final|interface)\s+)*'
  r'(class|enum|extension|mixin|typedef)\s+([A-Z]\w*)',
);
final RegExp _readmeBullet = RegExp(
  r'^- `([A-Z]\w*)` — (.+)$',
  multiLine: true,
);

/// Builds the WIDGETS.md content for the package at [root].
String buildIndex(String root) {
  final purposes = <String, String>{};
  final readme = File('$root/README.md');
  if (readme.existsSync()) {
    for (final m in _readmeBullet.allMatches(readme.readAsStringSync())) {
      purposes.putIfAbsent(m.group(1)!, () => m.group(2)!.trim());
    }
  }

  final groups = <String, List<String>>{};
  for (final path in _exportedFiles('$root/lib', 'j_flutter_ui.dart')) {
    final lines = File('$root/lib/$path').readAsLinesSync();
    final group = _groupOf(path);
    for (var i = 0; i < lines.length; i++) {
      final m = _declaration.firstMatch(lines[i]);
      if (m == null) continue;
      final name = m.group(2)!;
      final purpose = _docAbove(lines, i) ?? purposes[name] ?? '';
      groups
          .putIfAbsent(group, () => [])
          .add('| `$name` | ${m.group(1)} | ${_cell(purpose)} | `lib/$path` |');
    }
  }

  final out = StringBuffer()
    ..writeln('# Widget and token index')
    ..writeln()
    ..writeln(
      'Generated by `dart run tool/widget_index.dart`; do not edit by hand.',
    )
    ..writeln('Check here before writing a new widget or hard-coding a value.');
  for (final group in groups.keys.toList()..sort()) {
    out
      ..writeln()
      ..writeln('## $group')
      ..writeln()
      ..writeln('| Name | Kind | Purpose | File |')
      ..writeln('|---|---|---|---|');
    for (final row in groups[group]!) {
      out.writeln(row);
    }
  }
  return out.toString();
}

/// Library-relative paths of every file reachable through exports.
List<String> _exportedFiles(String libDir, String entry) {
  final seen = <String>{};
  final order = <String>[];
  void visit(String path) {
    if (!seen.add(path)) return;
    final file = File('$libDir/$path');
    if (!file.existsSync()) return;
    order.add(path);
    final dir = path.contains('/')
        ? path.substring(0, path.lastIndexOf('/'))
        : '';
    for (final m in _export.allMatches(file.readAsStringSync())) {
      final target = m.group(1)!;
      if (target.startsWith('package:') || target.startsWith('dart:')) continue;
      visit(_normalize(dir.isEmpty ? target : '$dir/$target'));
    }
  }

  visit(entry);
  return order.where((p) => p != entry).toList()..sort();
}

String _normalize(String path) {
  final parts = <String>[];
  for (final part in path.split('/')) {
    if (part == '..') {
      if (parts.isNotEmpty) parts.removeLast();
    } else if (part.isNotEmpty && part != '.') {
      parts.add(part);
    }
  }
  return parts.join('/');
}

String _groupOf(String path) {
  final dir = path.contains('/')
      ? path.substring(0, path.lastIndexOf('/'))
      : '';
  return dir.replaceFirst(RegExp(r'^src/ui/?'), '').isEmpty
      ? 'root'
      : dir.replaceFirst(RegExp(r'^src/ui/?'), '');
}

/// First sentence of the `///` comment directly above line [i], if any.
String? _docAbove(List<String> lines, int i) {
  final doc = <String>[];
  var j = i - 1;
  while (j >= 0 && lines[j].trimLeft().startsWith('@')) {
    j--;
  }
  while (j >= 0 && lines[j].trimLeft().startsWith('///')) {
    doc.insert(0, lines[j].trimLeft().substring(3).trim());
    j--;
  }
  if (doc.isEmpty) return null;
  final text = doc.join(' ').trim();
  final end = text.indexOf('. ');
  return end == -1 ? text : text.substring(0, end + 1);
}

String _cell(String text) => text.replaceAll('|', r'\|');

void main() {
  File(outputFile).writeAsStringSync(buildIndex(Directory.current.path));
  stdout.writeln('wrote $outputFile');
}
